- `create_entreprise_admin(admin_email text, entreprise_nom text)` — now also inserts a 30-day trial licence if the new entreprise has none.

## New Functions
- `get_licence_status()` — returns the current active licence row for the caller's entreprise, or NULL. SECURITY DEFINER so entreprise admins can check their own licence without direct table access being the only path.
