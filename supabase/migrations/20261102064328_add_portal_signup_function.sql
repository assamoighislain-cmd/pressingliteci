/*
# Add portal self-registration function

1. New Functions
- `portal_signup(p_nom text, p_telephone text, e_id int)` — SECURITY DEFINER function that
  allows a new client to self-register from the public client portal.
  Creates a client row linked to the entreprise's tenant_id and default boutique,
  auto-generates a portal_code (via the existing trigger), and returns the new code.
  Callable by anon role (no auth needed).

2. Security
- The function is SECURITY DEFINER with fixed search_path.
- It only creates clients for the entreprise matching e_id — it cannot be used to
  create clients in other tenants.
- It validates that the entreprise exists before inserting.
- It does not expose any other tenant's data.
- REVOKE EXECUTE FROM PUBLIC then GRANT to anon, authenticated only.
*/

CREATE OR REPLACE FUNCTION public.portal_signup(p_nom text, p_telephone text, e_id int)
RETURNS TABLE (portal_code text, client_id uuid)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
DECLARE
  v_ent RECORD;
  v_boutique_id uuid;
  v_client_id uuid;
  v_code text;
BEGIN
  -- Validate entreprise exists and get tenant info
  SELECT e.user_id, e.id INTO v_ent
  FROM entreprise e
  WHERE e.id = e_id;

  IF v_ent.user_id IS NULL THEN
    RAISE EXCEPTION 'invalid_entreprise';
  END IF;

  -- Validate name is not empty
  IF TRIM(p_nom) = '' THEN
    RAISE EXCEPTION 'name_required';
  END IF;

  -- Get the default boutique for this tenant
  SELECT b.id INTO v_boutique_id
  FROM boutiques b
  WHERE b.tenant_id = v_ent.user_id AND b.is_default = true
  LIMIT 1;

  -- If no default boutique, get any boutique for this tenant
  IF v_boutique_id IS NULL THEN
    SELECT b.id INTO v_boutique_id
    FROM boutiques b
    WHERE b.tenant_id = v_ent.user_id
    ORDER BY b.created_at ASC
    LIMIT 1;
  END IF;

  -- Insert the new client (portal_code auto-generated by trigger)
  INSERT INTO clients (nom, telephone, tenant_id, user_id, boutique_id, taux_remise)
  VALUES (TRIM(p_nom), NULLIF(TRIM(p_telephone), ''), v_ent.user_id, v_ent.user_id, v_boutique_id, 0)
  RETURNING id, portal_code INTO v_client_id, v_code;

  RETURN QUERY SELECT v_code, v_client_id;
END;
$$;

-- Grant access to anon (public portal, no auth) and authenticated
REVOKE EXECUTE ON FUNCTION public.portal_signup(text, text, int) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.portal_signup(text, text, int) TO anon, authenticated;
